//! Workflow coverage for project-level `node_modules` path diagnostics.

mod support;

use support::assertions::parse_json_output;
use support::{TempProject, lpm};

#[cfg(unix)]
#[test]
fn doctor_reports_symlinked_node_modules_with_an_actionable_remediation() {
    let project = TempProject::empty(r#"{"name":"doctor-node-modules","version":"1.0.0"}"#);
    let target = tempfile::tempdir().expect("create node_modules target");
    std::os::unix::fs::symlink(target.path(), project.path().join("node_modules"))
        .expect("create project node_modules symlink");

    let output = lpm(&project)
        .args(["doctor", "--json"])
        .output()
        .expect("run lpm doctor --json");
    let json = parse_json_output(&output.stdout);
    let check = json["checks"]
        .as_array()
        .expect("doctor checks array")
        .iter()
        .find(|check| check["code"] == "node_modules_symlinked")
        .unwrap_or_else(|| panic!("doctor must report node_modules_symlinked: {json}"));

    assert_eq!(
        check["detail"].as_str(),
        Some("is a symlink or directory junction — run: lpm doctor --fix, then run: lpm install"),
        "doctor must not send this project back into the failing install without naming the symlink",
    );
    assert_eq!(check["severity"].as_str(), Some("fail"));
    assert!(
        json["checks"]
            .as_array()
            .expect("doctor checks array")
            .iter()
            .all(|check| check["code"] != "node_modules_no_store"),
        "doctor must not misclassify the symlink as an incomplete install: {json}",
    );
    let detail = check["detail"].as_str().expect("symlink check detail");
    assert!(!detail.contains("store clean"), "detail: {detail}");
    assert!(!detail.contains("cache prune"), "detail: {detail}");
}

#[test]
fn doctor_fix_replaces_only_the_node_modules_link_and_preserves_its_target() {
    let project = TempProject::empty(r#"{"name":"doctor-node-modules-fix","version":"1.0.0"}"#);
    lpm_lockfile::Lockfile::new()
        .write_all(&project.path().join(lpm_lockfile::LOCKFILE_NAME))
        .expect("seed lockfiles");
    let target = tempfile::tempdir().expect("create node_modules target");
    std::fs::write(target.path().join("sentinel"), b"must survive").expect("write target sentinel");
    let node_modules = project.path().join("node_modules");
    lpm_common::create_dir_symlink_or_junction(target.path(), &node_modules)
        .expect("create project node_modules link");

    let output = lpm(&project)
        .args([
            "--registry",
            "http://127.0.0.1:1",
            "--insecure",
            "--json",
            "doctor",
            "--fix",
            "--yes",
        ])
        .output()
        .expect("run lpm doctor --fix --json");
    let json = parse_json_output(&output.stdout);

    assert_eq!(
        std::fs::read(target.path().join("sentinel")).expect("read target sentinel"),
        b"must survive",
        "doctor must never mutate the node_modules link target",
    );
    let metadata = node_modules
        .symlink_metadata()
        .expect("doctor must create a replacement node_modules directory");
    assert!(
        metadata.is_dir() && !lpm_common::is_symlink_or_junction(&metadata),
        "doctor must replace the link entry with a real directory"
    );
    assert!(
        json["fixes_applied"]
            .as_array()
            .expect("fixes_applied array")
            .iter()
            .any(|fix| fix == "replaced project node_modules link with a real directory"),
        "doctor must report the node_modules repair: {json}"
    );
}
