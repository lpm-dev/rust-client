//! Workflow coverage for project-level `node_modules` path validation.

mod support;

use support::mock_registry::MockRegistry;
use support::{TempProject, lpm_with_registry};

fn link_node_modules(project_path: &std::path::Path, target: &std::path::Path) {
    lpm_common::create_dir_symlink_or_junction(target, &project_path.join("node_modules"))
        .expect("create project node_modules link");
}

#[tokio::test]
async fn install_rejects_symlinked_node_modules_before_registry_access() {
    let registry = MockRegistry::start().await;
    registry
        .with_manifest_package(
            serde_json::json!({
                "name": "preflight-dependency",
                "version": "1.0.0"
            }),
            &[],
        )
        .await;
    let project = TempProject::empty(
        r#"{
  "name": "symlinked-node-modules",
  "version": "1.0.0",
  "dependencies": { "preflight-dependency": "1.0.0" }
}"#,
    );
    let target = tempfile::tempdir().expect("create node_modules target");
    link_node_modules(project.path(), target.path());

    let output = lpm_with_registry(&project, &registry.url())
        .args([
            "install",
            "--no-security-summary",
            "--no-skills",
            "--no-editor-setup",
        ])
        .output()
        .expect("run install with symlinked node_modules");

    assert!(
        !output.status.success(),
        "install must reject a project-level node_modules link"
    );
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains("Project layout error")
            && stderr.contains(&project.path().join("node_modules").display().to_string()),
        "install must identify the invalid project path; got:\n{stderr}"
    );
    let requests = registry
        .server()
        .received_requests()
        .await
        .expect("read registry requests");
    assert!(
        requests.is_empty(),
        "project layout preflight must run before registry access; requests={requests:?}"
    );
}

#[tokio::test]
async fn recursive_install_rejects_symlinked_member_node_modules_before_registry_access() {
    let registry = MockRegistry::start().await;
    registry
        .with_manifest_package(
            serde_json::json!({
                "name": "member-preflight-dependency",
                "version": "1.0.0"
            }),
            &[],
        )
        .await;
    let project = TempProject::empty(
        r#"{
  "name": "recursive-symlinked-node-modules",
  "version": "1.0.0",
  "private": true,
  "workspaces": ["packages/*"]
}"#,
    );
    project.write_file(
        "packages/app/package.json",
        r#"{
  "name": "recursive-app",
  "version": "1.0.0",
  "dependencies": { "member-preflight-dependency": "1.0.0" }
}"#,
    );
    let member_path = project.path().join("packages/app");
    let target = tempfile::tempdir().expect("create member node_modules target");
    link_node_modules(&member_path, target.path());

    let output = lpm_with_registry(&project, &registry.url())
        .args([
            "install",
            "--recursive",
            "--no-security-summary",
            "--no-skills",
            "--no-editor-setup",
        ])
        .output()
        .expect("run recursive install with symlinked member node_modules");

    assert!(
        !output.status.success(),
        "recursive install must reject a member-level node_modules link"
    );
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains("Project layout error")
            && stderr.contains(&member_path.join("node_modules").display().to_string()),
        "recursive install must identify the invalid workspace member; got:\n{stderr}"
    );
    let requests = registry
        .server()
        .received_requests()
        .await
        .expect("read registry requests");
    assert!(
        requests.is_empty(),
        "recursive layout preflight must validate all targets before registry access; requests={requests:?}"
    );
}
