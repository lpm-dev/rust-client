function FallbackIcon({ label }: { label: string }) {
  return <span className={styles.fallback}>{label.slice(0, 2)}</span>;
}

function AgentGlyph({ agent, label }: Pick<SkillTarget, 'agent' | 'label'>) {
  switch (agent) {
    case 'codex':
      return <CodexIcon />;
    case 'claude-code':
      return <ClaudeIcon />;
    case 'kimi':
      return <KimiIcon />;
    case 'pi':
      return <span className={styles.pi}>π</span>;
    case 'cursor':
      return <CursorIcon />;
    case 'opencode':
      return <OpenCodeIcon />;
    case 'grok':
      return <GrokIcon />;
    default:
      return <FallbackIcon label={label} />;
  }
}

export function AgentIcons({ targets }: AgentIconsProps) {
  const labels = targets.map(({ label }) => label).join(', ');
  return (
    <span className={styles.group} role="img" aria-label={`Agents: ${labels}`}>
      {targets.map(({ agent, label }) => (
        <span
          key={agent}
          className={styles.icon}
          data-agent-icon={agent}
          title={label}
          aria-hidden="true"
        >
          <AgentGlyph agent={agent} label={label} />
        </span>
      ))}
    </span>
  );
}
