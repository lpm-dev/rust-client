pub(super) struct SetupRegistry {
    service_base: String,
    endpoint: String,
    auth_scope: String,
}

/// The service base URL for a `setup --registry` value written as its
/// `/api/registry` endpoint: stored logins are keyed by the base. `None`
/// keeps any other value as written, the key a login with that value stored,
/// and a value `setup` rejects, which it reports itself.
pub(crate) fn setup_registry_service_base(raw: &str) -> Option<String> {
    if !raw.trim_end_matches('/').ends_with("/api/registry") {
        return None;
    }
    SetupRegistry::parse(raw)
        .ok()
        .map(|registry| registry.service_base)
}

impl SetupRegistry {
    pub(super) fn parse(raw: &str) -> Result<Self, LpmError> {
        if raw.is_empty() || raw.trim() != raw || raw.chars().any(char::is_control) {
            return Err(LpmError::Script(
                "the registry URL contains whitespace or control characters".into(),
            ));
        }
        let parsed = reqwest::Url::parse(raw)
            .map_err(|error| LpmError::Script(format!("invalid registry URL: {error}")))?;
        if !matches!(parsed.scheme(), "http" | "https") || parsed.host_str().is_none() {
            return Err(LpmError::Script(
                "the registry URL must use https://, or http:// for a loopback host".into(),
            ));
        }
        if parsed.scheme() == "http" && !lpm_registry::is_localhost_url(parsed.as_str()) {
            return Err(LpmError::Script(
                "the registry URL must use https:// unless its host is loopback".into(),
            ));
        }
        if !parsed.username().is_empty() || parsed.password().is_some() {
            return Err(LpmError::Script(
                "the registry URL must not contain credentials".into(),
            ));
        }
        if parsed.query().is_some() || parsed.fragment().is_some() {
            return Err(LpmError::Script(
                "the registry URL must not contain a query or fragment".into(),
            ));
        }

        let input_path = parsed.path().trim_end_matches('/');
        let base_path = input_path
            .strip_suffix("/api/registry")
            .unwrap_or(input_path);
        let endpoint_path = if input_path.ends_with("/api/registry") {
            input_path.to_string()
        } else if input_path.is_empty() {
            "/api/registry".to_string()
        } else {
            format!("{input_path}/api/registry")
        };

        let mut service_url = parsed.clone();
        service_url.set_path(base_path);
        let service_base = service_url.as_str().trim_end_matches('/').to_string();
        let mut endpoint_url = parsed;
        endpoint_url.set_path(&endpoint_path);
        let endpoint = endpoint_url.as_str().trim_end_matches('/').to_string();
        let without_scheme = endpoint
            .strip_prefix("https://")
            .or_else(|| endpoint.strip_prefix("http://"))
            .expect("accepted registry schemes have a serialized prefix");
        let auth_scope = format!("//{without_scheme}/");

        Ok(Self {
            service_base,
            endpoint,
            auth_scope,
        })
    }

    pub(super) fn service_base(&self) -> &str {
        &self.service_base
    }

    pub(super) fn endpoint(&self) -> &str {
        &self.endpoint
    }

    pub(super) fn auth_scope(&self) -> &str {
        &self.auth_scope
    }

    pub(super) fn token_url(&self, operation: &str) -> String {
        format!("{}/-/token/{operation}", self.endpoint)
    }
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct TokenReplaceResponse {
    token_id: String,
    scope: String,
    expires_at: String,
}

struct PendingSetupToken {
    token: String,
    token_id: String,
    previous_bearer: Option<String>,
}

/// What a failed setup restores: the `.npmrc` it wrote. A rule it added to
/// `.gitignore` stays, as it only keeps files out of git, and another
/// command may have added its own since.
#[derive(Clone, Copy, Default)]
struct SetupRollback<'a> {
    npmrc: Option<(&'a Path, &'a str, Option<&'a str>)>,
}

impl<'a> SetupRollback<'a> {
    fn with_npmrc(
        mut self,
        npmrc_path: &'a Path,
        expected_npmrc: &'a str,
        original_npmrc: Option<&'a str>,
    ) -> Self {
        self.npmrc = Some((npmrc_path, expected_npmrc, original_npmrc));
        self
    }

    fn restore(self) -> Vec<String> {
        let mut errors = Vec::new();
        if let Some((npmrc_path, expected_npmrc, original_npmrc)) = self.npmrc
            && let Err(error) = restore_file_if_unchanged(
                npmrc_path,
                expected_npmrc,
                original_npmrc,
                lpm_common::NPMRC_FILE_SIZE_CAP_BYTES,
                true,
            )
        {
            errors.push(format!("failed to restore .npmrc: {error}"));
        }
        errors
    }
}

/// Generate a read-only .npmrc token for local development.
///
/// Creates a scoped read-only token and writes it to the project's .npmrc,
/// which it keeps out of Git with `.gitignore`. When Git tracks the
/// project's .npmrc, the token goes to npm's user configuration instead, as
/// [`setup_npmrc_destination`] explains.
///
/// Default: scoped config (`@lpm.dev:registry=`) — only LPM packages go through lpm.dev.
pub async fn run(
    client: &RegistryClient,
    project_dir: &Path,
    registry_url: &str,
    days: u32,
    json_output: bool,
) -> Result<(), LpmError> {
    if !(1..=90).contains(&days) {
        return Err(LpmError::Script(
            "--days must be between 1 and 90".to_string(),
        ));
    }
    let registry = SetupRegistry::parse(registry_url)?;

    let target = setup_npmrc_destination(project_dir, &registry, &NpmUserConfig::from_env())?;

    let pkg_json_path = project_dir.join("package.json");
    let npmrc_path = target.path.clone();

    let package_json_content = match lpm_common::read_text_file_capped(
        &pkg_json_path,
        lpm_common::CONFIG_FILE_SIZE_CAP_BYTES,
    ) {
        Ok(content) => Some(content),
        Err(lpm_common::BoundedReadError::NotFound { .. }) => None,
        Err(error) => return Err(error.into()),
    };
    let existing_npmrc_state = match lpm_common::read_text_file_capped_nofollow(
        &npmrc_path,
        lpm_common::NPMRC_FILE_SIZE_CAP_BYTES,
    ) {
        Ok(content) => Some(content),
        Err(lpm_common::BoundedReadError::NotFound { .. }) => None,
        Err(error) => return Err(error.into()),
    };
    let existing_npmrc = existing_npmrc_state.as_deref().unwrap_or_default();

    if package_json_content.is_none() && !json_output {
        install_ui::warn("No package.json found. Run this command in your project root.");
    }

    let project_name = if let Some(content) = package_json_content {
        serde_json::from_str::<serde_json::Value>(&content)
            .ok()
            .and_then(|v| v.get("name")?.as_str().map(|s| s.to_string()))
            .map_or_else(
                || "project".to_string(),
                |name| {
                    name.chars()
                        .map(|c| {
                            if c.is_alphanumeric() || c == '.' || c == '-' || c == '_' {
                                c
                            } else {
                                '-'
                            }
                        })
                        .collect::<String>()
                },
            )
    } else {
        "project".to_string()
    };

    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_err(|error| LpmError::Script(format!("system clock is before Unix epoch: {error}")))?
        .as_secs();
    let days_since_epoch = now / 86400;
    let today = format!("{days_since_epoch}");
    // A token in npm's user configuration serves every project on the
    // machine, so it isn't named after the one that created it.
    let token_name = if target.is_user_config() {
        format!("npmrc-user-config-{today}")
    } else {
        format!("npmrc-{project_name}-{today}")
    };

    let registry_line = format!("@lpm.dev:registry={}/", registry.endpoint());
    if let Some(existing_registry) = local_setup_registry_url(existing_npmrc)
        && existing_registry != registry.endpoint()
    {
        return Err(target.foreign_registry_error(
            "setup-local token",
            &existing_registry,
            "finish replacement safely",
        ));
    }
    reject_legacy_ci_retirement_state(existing_npmrc)?;
    let pending = match pending_setup_token(existing_npmrc, registry.auth_scope())? {
        Some(pending) => pending,
        None => PendingSetupToken {
            token: generate_project_token()?,
            token_id: generate_uuid_v4()?,
            previous_bearer: local_project_token_bearer(existing_npmrc, registry.auth_scope())?,
        },
    };

    if !existing_npmrc.is_empty() {
        let has_custom_registry = existing_npmrc.lines().any(|line| {
            line.starts_with("registry=")
                && !line.contains("registry.npmjs.org")
                && !line.contains("lpm.dev")
        });
        if has_custom_registry && !json_output {
            install_ui::phase("Found existing custom default registry. Using scoped mode.");
        }
    }

    let gitignore_path = project_dir.join(".gitignore");
    let (npmrc_ignore, ignore_warnings) = lpm_common::project_secret::prepare_secret_destination(
        project_dir,
        &npmrc_path,
        target.ignore_file(lpm_common::project_secret::IgnoreFile::ProjectGitignore),
        lpm_common::project_secret::IgnoreFailure::Refuse,
    )
    .map_err(LpmError::from)?;
    let gitignore_updated = npmrc_ignore.added_to().contains(&gitignore_path);
    let rollback = SetupRollback::default();

    let previous_marker = pending
        .previous_bearer
        .as_ref()
        .map_or_else(String::new, |bearer| {
            format!("{PREVIOUS_TOKEN_BEARER_PREFIX}{bearer}\n")
        });
    let pending_config = format!(
        "{GENERATED_HEADER}\n{PENDING_TOKEN_ID_PREFIX}{}\n{previous_marker}{registry_line}\n{}:_authToken={}\n{GENERATED_END}",
        pending.token_id,
        registry.auth_scope(),
        pending.token
    );
    let pending_content = replace_generated_block(existing_npmrc, &pending_config);
    // Conditional, as npm's user configuration can change under another
    // command, such as `npm login`, between the read above and this write.
    if let Err(error) = write_npmrc_if_unchanged(&npmrc_path, existing_npmrc, &pending_content) {
        return Err(rollback_files(error, rollback));
    }
    let rollback = rollback.with_npmrc(
        &npmrc_path,
        &pending_content,
        existing_npmrc_state.as_deref(),
    );

    if !json_output {
        install_ui::phase("Creating read-only token...");
    }

    let mut body = serde_json::json!({
        "token": pending.token,
        "tokenId": pending.token_id,
        "scope": "read",
        "name": token_name,
        "expiryDays": days,
    });
    if let Some(previous_bearer) = &pending.previous_bearer {
        body["previousTokenHash"] =
            serde_json::Value::String(hex::encode(Sha256::digest(previous_bearer.as_bytes())));
    }
    let url = registry.token_url("replace-project");
    let mut response = send_token_replacement(client, &url, &body, rollback).await?;
    let mut warnings = ignore_warnings;
    if response.status() == reqwest::StatusCode::NOT_FOUND && pending.previous_bearer.is_some() {
        let status = response.status();
        let parsed =
            lpm_registry::parse_capped_api_json(response, "project token replacement error").await;
        if !refused_inactive_predecessor(parsed.as_ref().ok()) {
            return Err(replacement_client_error(
                status,
                parsed,
                &pending.token,
                rollback,
            ));
        }
        // A token revoked in the dashboard, or one that isn't this account's
        // setup token, leaves nothing to retire: set up a new one instead.
        if let Some(fields) = body.as_object_mut() {
            fields.remove("previousTokenHash");
        }
        warnings.push(INACTIVE_PREDECESSOR_WARNING.to_string());
        response = send_token_replacement(client, &url, &body, rollback).await?;
    }

    if !response.status().is_success() {
        let status = response.status();
        let parsed =
            lpm_registry::parse_capped_api_json(response, "project token replacement error").await;
        if !status.is_client_error() {
            let detail = parsed
                .ok()
                .and_then(|value: serde_json::Value| {
                    value
                        .get("error")
                        .and_then(serde_json::Value::as_str)
                        .map(|message| sanitize_registry_message(message, &pending.token))
                })
                .unwrap_or_else(|| "Registry returned an ambiguous failure".to_string());
            return Err(pending_recovery_error(format!("{detail} ({status})")));
        }
        return Err(replacement_client_error(
            status,
            parsed,
            &pending.token,
            rollback,
        ));
    }

    let replaced_value: serde_json::Value =
        match lpm_registry::parse_capped_api_json(response, "project token replacement response")
            .await
        {
            Ok(value) => value,
            Err(error) => {
                return Err(pending_recovery_error(sanitize_registry_message(
                    &error.to_string(),
                    &pending.token,
                )));
            }
        };
    let replaced: TokenReplaceResponse = match serde_json::from_value(replaced_value) {
        Ok(replaced) => replaced,
        Err(error) => {
            return Err(pending_recovery_error(format!(
                "invalid project token replacement response: {error}"
            )));
        }
    };
    if replaced.token_id != pending.token_id
        || replaced.scope != "read"
        || !lpm_common::Timestamp::parse_rfc3339(&replaced.expires_at)
            .is_ok_and(|expires| expires > lpm_common::Timestamp::now())
    {
        return Err(pending_recovery_error(
            "invalid project token replacement response: expected the requested read-only token ID and a future expiry",
        ));
    }
    let expires_at = replaced.expires_at;

    let lpm_config = format!(
        "{GENERATED_HEADER}\n{TOKEN_ID_PREFIX}{}\n{registry_line}\n{}:_authToken={}\n{GENERATED_END}",
        pending.token_id,
        registry.auth_scope(),
        pending.token
    );
    let final_content = replace_generated_block(&pending_content, &lpm_config);
    if let Err(error) = write_npmrc_if_unchanged(&npmrc_path, &pending_content, &final_content) {
        return Err(pending_recovery_error(format!(
            "the Registry committed the replacement, but .npmrc could not be finalized: {error}"
        )));
    }

    if !json_output {
        install_ui::done("Read-only token created.");
    }

    if json_output {
        let json = serde_json::json!({
            "success": true,
            "npmrc_path": npmrc_path.display().to_string(),
            "npmrc_location": target.location(),
            "gitignore_path": (!target.is_user_config()).then(|| gitignore_path.display().to_string()),
            "proxy": false,
            "scope": replaced.scope,
            "expires_at": expires_at,
            "expiry_days": days,
            "gitignore_updated": gitignore_updated,
            "warnings": warnings,
        });
        let rendered = serde_json::to_string_pretty(&json).map_err(|error| {
            LpmError::Registry(format!("failed to encode JSON output: {error}"))
        })?;
        println!("{rendered}");
    } else {
        match target.destination {
            NpmrcDestination::Project => {
                install_ui::done(".npmrc configured with read-only LPM token.");
            }
            NpmrcDestination::User { .. } => install_ui::done_untrusted(&format!(
                "{} has the read-only LPM token.",
                npmrc_path.display()
            )),
        }
        for note in target.user_destination_notes(&registry, SetupCommand::Local) {
            install_ui::phase_untrusted(&note);
        }
        for warning in &warnings {
            crate::output::warn(warning);
        }
        if gitignore_updated {
            install_ui::phase(".npmrc added to .gitignore to prevent token leaks.");
        }
        install_ui::phase("Only @lpm.dev packages will route through lpm.dev.");
        if !expires_at.is_empty() {
            install_ui::phase_line(crate::install_ui::terminal_line!(
                "{} {} ({})",
                install_ui::dim("Token expires:"),
                expires_at,
                install_ui::yellow(&format_days_label(days))
            ));
        }
        install_ui::phase("Run `lpm setup local` again to refresh when expired.");
    }

    Ok(())
}

/// The `.npmrc` that `lpm setup local` and `lpm setup ci npmrc` write
/// their generated block to.
pub(super) struct SetupNpmrc {
    pub(super) path: PathBuf,
    pub(super) destination: NpmrcDestination,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum NpmrcDestination {
    /// The project's own `.npmrc`, which Git doesn't track.
    Project,
    /// npm's user configuration, because Git tracks the project's `.npmrc`.
    User {
        /// How the tracked file routes `@lpm.dev`, which other machines rely on.
        tracked_route: TrackedScopeRoute,
        /// Whether the file is `~/.npmrc`, the only one Bun reads.
        bun_reads_it: bool,
    },
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum TrackedScopeRoute {
    /// The tracked `.npmrc` doesn't route `@lpm.dev`.
    Missing,
    /// It routes `@lpm.dev` to the registry. Bun needs the URL to end with
    /// a slash, and the project line takes precedence over the generated one.
    Routed { trailing_slash: bool },
}

/// Which command writes the block, for the notes and errors that differ.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum SetupCommand {
    Local,
    Ci,
}

impl SetupNpmrc {
    /// The value the JSON output reports for where the block went.
    pub(super) fn location(&self) -> &'static str {
        match self.destination {
            NpmrcDestination::Project => "project",
            NpmrcDestination::User { .. } => "user",
        }
    }

    pub(super) fn is_user_config(&self) -> bool {
        matches!(self.destination, NpmrcDestination::User { .. })
    }

    /// The ignore file that keeps the destination out of Git: a rule only
    /// this machine sees for npm's user configuration, which isn't project
    /// state.
    pub(super) fn ignore_file(
        &self,
        project_ignore: lpm_common::project_secret::IgnoreFile,
    ) -> lpm_common::project_secret::IgnoreFile {
        match self.destination {
            NpmrcDestination::Project => project_ignore,
            NpmrcDestination::User { .. } => {
                lpm_common::project_secret::IgnoreFile::RepositoryExclude
            }
        }
    }

    /// The error for a generated block in the destination that belongs to
    /// `existing_registry`, which a run for another registry must not replace.
    pub(super) fn foreign_registry_error(
        &self,
        block: &str,
        existing_registry: &str,
        finish: &str,
    ) -> LpmError {
        let existing_registry = lpm_common::sanitize_terminal_inline(existing_registry);
        match self.destination {
            NpmrcDestination::Project => LpmError::Script(format!(
                "the {block} belongs to {existing_registry}; rerun with its registry to {finish}"
            )),
            NpmrcDestination::User { .. } => LpmError::Script(format!(
                "npm's user configuration {} holds the {block} for {existing_registry}, and it has room for one generated block. Rerun with `--registry {existing_registry}`, or remove that block first",
                lpm_common::sanitize_terminal_inline(&self.path.display().to_string())
            )),
        }
    }

    /// Lines the human output adds after a write to npm's user configuration.
    pub(super) fn user_destination_notes(
        &self,
        registry: &SetupRegistry,
        command: SetupCommand,
    ) -> Vec<String> {
        let NpmrcDestination::User {
            tracked_route,
            bun_reads_it,
        } = self.destination
        else {
            return Vec::new();
        };
        let mut notes = vec![
            "Git tracks the project's .npmrc, so the token went to npm's user configuration instead. Every project on this machine uses it.".to_string(),
        ];
        match tracked_route {
            TrackedScopeRoute::Missing => notes.push(format!(
                "Add `@lpm.dev:registry={}/` to the tracked .npmrc so other machines route @lpm.dev packages to this registry too.",
                registry.endpoint()
            )),
            TrackedScopeRoute::Routed {
                trailing_slash: false,
            } => notes.push(
                "End the @lpm.dev:registry URL in the tracked .npmrc with a slash. Bun drops the last part of a registry URL that has none.".to_string(),
            ),
            TrackedScopeRoute::Routed {
                trailing_slash: true,
            } => {}
        }
        if !bun_reads_it {
            notes.push(
                "NPM_CONFIG_USERCONFIG names this file. Bun reads only ~/.npmrc, so Bun won't use the token.".to_string(),
            );
        }
        if command == SetupCommand::Ci {
            notes.push(format!(
                "The token stays in {} after the job. On a runner that other jobs share, remove the generated block when the job ends, or point NPM_CONFIG_USERCONFIG at a file in the job's temporary directory.",
                self.path.display()
            ));
        }
        notes
    }
}

/// npm's user configuration file: `NPM_CONFIG_USERCONFIG` when it names one,
/// else `.npmrc` in the home directory. npm, pnpm and Yarn 1 honor the
/// variable. Bun reads `~/.npmrc` alone, which `home_npmrc` names.
pub(super) struct NpmUserConfig {
    pub(super) path: Option<PathBuf>,
    pub(super) home_npmrc: Option<PathBuf>,
}

impl NpmUserConfig {
    pub(super) fn from_env() -> Self {
        let home = lpm_common::npm_home_dir();
        Self {
            path: lpm_common::npm_user_config_path(home.as_deref()),
            home_npmrc: home.map(|home| home.join(".npmrc")),
        }
    }
}

/// The settings that make a request to a registry carry a credential. npm
/// takes the token first, so a project `_authToken` overrides a user one; the
/// others in a committed file are a leaked secret all the same.
const CREDENTIAL_KEYS: [&str; 5] = [
    "_authToken",
    "_auth",
    "_password",
    "username",
    "tokenHelper",
];

/// The first credential setting for `auth_scope` in `settings`.
fn credential_for_scope<'a>(
    settings: &'a [lpm_common::NpmrcIniSetting<'_>],
    auth_scope: &str,
) -> Option<&'a str> {
    settings.iter().find_map(|setting| {
        let field = setting.key.strip_prefix(auth_scope)?.strip_prefix(':')?;
        CREDENTIAL_KEYS.contains(&field).then_some(&*setting.key)
    })
}

/// The `@lpm.dev` route in `settings`, as written.
fn scope_route<'a>(settings: &'a [lpm_common::NpmrcIniSetting<'_>]) -> Option<&'a str> {
    settings
        .iter()
        .find(|setting| &*setting.key == "@lpm.dev:registry")
        .and_then(|setting| setting.values.last())
        .map(|value| value.value.as_ref())
}

/// Chooses the `.npmrc` that will hold the bearer, before anything writes it.
///
/// An `.npmrc` that Git doesn't track takes the generated block, as it
/// always has. One that Git tracks keeps the settings the team shares and
/// takes no token: the block goes to npm's user configuration instead. That
/// works only while the tracked file sets no credential for the registry,
/// because npm, Yarn 1 and Bun prefer a project setting to a user one, and
/// only while it routes `@lpm.dev` to the same registry, if it routes the
/// scope at all. The user configuration must be a regular file, or none yet,
/// in a directory that exists, and must not set its own credential or route
/// for the registry outside the generated block: the block would override
/// them for every project. A repository where Git can't tell whether the
/// file is tracked is refused, as is a user configuration that is the
/// tracked file.
pub(super) fn setup_npmrc_destination(
    project_dir: &Path,
    registry: &SetupRegistry,
    user_config: &NpmUserConfig,
) -> Result<SetupNpmrc, LpmError> {
    use lpm_common::project_git::{GitProbeError, repository_marker_above, tracked_entries};
    let project_npmrc = project_dir.join(".npmrc");
    let project = || SetupNpmrc {
        path: project_npmrc.clone(),
        destination: NpmrcDestination::Project,
    };
    match tracked_entries(project_dir, &[".npmrc"]) {
        Ok(None) => Ok(project()),
        Err(GitProbeError::GitMissing(_)) if !repository_marker_above(project_dir) => Ok(project()),
        Ok(Some(tracked)) if tracked.is_empty() => Ok(project()),
        Ok(Some(tracked)) => {
            let tracked_route = tracked_npmrc_route(&project_npmrc, registry)?;
            let path = user_config.path.as_deref().ok_or_else(|| {
                LpmError::ProjectFile(
                    "Git tracks the project's .npmrc, so the token belongs in npm's user configuration, but there is no home directory to hold it. Set HOME, or name the file with NPM_CONFIG_USERCONFIG, then run the command again".into(),
                )
            })?;
            let path = std::path::absolute(path).map_err(|error| {
                LpmError::ProjectFile(format!(
                    "npm's user configuration {} has no usable path: {error}",
                    path.display()
                ))
            })?;
            if same_file_location(&path, &project_npmrc) {
                return Err(LpmError::ProjectFile(format!(
                    "refused to write a Git-tracked .npmrc because it will contain a bearer token: npm's user configuration is that file. Point NPM_CONFIG_USERCONFIG at a file outside the repository, or untrack .npmrc with `{}`, then run the command again",
                    tracked.untrack_command()
                )));
            }
            check_user_config(&path, registry)?;
            let bun_reads_it = user_config
                .home_npmrc
                .as_deref()
                .is_some_and(|home_npmrc| same_file_location(&path, home_npmrc));
            Ok(SetupNpmrc {
                path,
                destination: NpmrcDestination::User {
                    tracked_route,
                    bun_reads_it,
                },
            })
        }
        Err(GitProbeError::GitMissing(reason)) => Err(LpmError::ProjectFile(format!(
            "refused to write .npmrc: git could not be run ({reason}) in a project inside a git repository, so Git tracking can't be inspected and the bearer token .npmrc will hold could be committed. Put git on PATH, then run the command again"
        ))),
        Err(GitProbeError::Failed(reason)) => Err(LpmError::ProjectFile(format!(
            "refused to write .npmrc: Git tracking can't be inspected, so it can't tell whether .npmrc is tracked ({reason}). Repair the repository, then run the command again"
        ))),
    }
}

/// How the tracked project `.npmrc` routes `@lpm.dev`. It is refused when it
/// sets a credential for the registry, which would override the token in
/// npm's user configuration, or routes the scope somewhere else, where that
/// token would never be sent.
fn tracked_npmrc_route(
    project_npmrc: &Path,
    registry: &SetupRegistry,
) -> Result<TrackedScopeRoute, LpmError> {
    let content = match lpm_common::read_text_file_capped_nofollow(
        project_npmrc,
        lpm_common::NPMRC_FILE_SIZE_CAP_BYTES,
    ) {
        Ok(content) => content,
        // Deleted from the work tree: npm reads no project settings.
        Err(lpm_common::BoundedReadError::NotFound { .. }) => {
            return Ok(TrackedScopeRoute::Missing);
        }
        Err(error) => {
            return Err(LpmError::ProjectFile(format!(
                "Git tracks the project's .npmrc, and LPM CLI could not read it to make sure that it sets no credential of its own: {error}"
            )));
        }
    };
    let mut diagnostics = Vec::new();
    let settings = lpm_common::parse_npmrc_ini_settings(&content, ".npmrc", &mut diagnostics);
    if let Some(key) = credential_for_scope(&settings, registry.auth_scope()) {
        return Err(LpmError::ProjectFile(format!(
            "Git tracks the project's .npmrc, and it sets `{}`. npm, Yarn 1 and Bun would use that setting instead of a token in npm's user configuration. Remove it from the tracked file, then run the command again. If it held a secret, revoke that too, because the repository has it",
            lpm_common::sanitize_terminal_inline(key)
        )));
    }
    match scope_route(&settings) {
        None => Ok(TrackedScopeRoute::Missing),
        Some(routed) if normalize_registry_url(routed) == registry.endpoint() => {
            Ok(TrackedScopeRoute::Routed {
                trailing_slash: routed.ends_with('/'),
            })
        }
        Some(routed) => {
            let routed =
                lpm_common::sanitize_terminal_inline(&normalize_registry_url(routed)).to_string();
            Err(LpmError::ProjectFile(format!(
                "Git tracks the project's .npmrc, and it routes @lpm.dev packages to {routed}, so a token for {} would never be sent. Run the command with `--registry {routed}`, or change that line",
                registry.endpoint(),
            )))
        }
    }
}

/// Refuses a user configuration that can't take the generated block: a
/// link, which the write would replace with a file, one in a directory that
/// doesn't exist, and one whose own settings for the registry the block
/// would override for every project.
fn check_user_config(path: &Path, registry: &SetupRegistry) -> Result<(), LpmError> {
    let shown = lpm_common::sanitize_terminal_inline(&path.display().to_string()).to_string();
    if std::fs::symlink_metadata(path).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
        return Err(LpmError::ProjectFile(format!(
            "npm's user configuration {} is a symbolic link, and LPM CLI doesn't write a token through one. Point NPM_CONFIG_USERCONFIG at a regular file, or add the token line to the file the link leads to yourself",
            shown
        )));
    }
    if !path.parent().is_some_and(Path::is_dir) {
        return Err(LpmError::ProjectFile(format!(
            "the directory of npm's user configuration {} doesn't exist. Create it, or point NPM_CONFIG_USERCONFIG at a file in a directory that exists",
            shown
        )));
    }
    let content = match lpm_common::read_text_file_capped_nofollow(
        path,
        lpm_common::NPMRC_FILE_SIZE_CAP_BYTES,
    ) {
        Ok(content) => content,
        Err(lpm_common::BoundedReadError::NotFound { .. }) => return Ok(()),
        Err(error) => return Err(error.into()),
    };
    let outside = lines_outside_generated_blocks(&content).join("\n");
    let mut diagnostics = Vec::new();
    let settings = lpm_common::parse_npmrc_ini_settings(&outside, ".npmrc", &mut diagnostics);
    if let Some(key) = credential_for_scope(&settings, registry.auth_scope()) {
        return Err(LpmError::ProjectFile(format!(
            "npm's user configuration {} already sets `{}`, and the generated token would take its place in every project. Remove that setting, then run the command again",
            shown,
            lpm_common::sanitize_terminal_inline(key)
        )));
    }
    if let Some(routed) = scope_route(&settings)
        && normalize_registry_url(routed) != registry.endpoint()
    {
        return Err(LpmError::ProjectFile(format!(
            "npm's user configuration {} routes @lpm.dev packages to {}, and the generated block would send them to {} in every project. Remove that line, or run the command with `--registry {}`",
            shown,
            lpm_common::sanitize_terminal_inline(&normalize_registry_url(routed)),
            registry.endpoint(),
            lpm_common::sanitize_terminal_inline(&normalize_registry_url(routed)),
        )));
    }
    Ok(())
}

/// Whether two paths name the same file, once the directories on the way
/// resolve. Either file may not exist yet.
fn same_file_location(left: &Path, right: &Path) -> bool {
    let resolve = |path: &Path| {
        let (Some(parent), Some(name)) = (path.parent(), path.file_name()) else {
            return path.to_path_buf();
        };
        std::fs::canonicalize(parent)
            .map_or_else(|_| path.to_path_buf(), |parent| parent.join(name))
    };
    resolve(left) == resolve(right)
}

const INACTIVE_PREDECESSOR_WARNING: &str = "The token .npmrc held is no longer active for this account, so LPM CLI set up a new one instead of replacing it. If it was revoked in the dashboard, nothing else is needed.";

/// Sends the setup-token replacement. A response that never arrives leaves
/// the pending token in `.npmrc` for a rerun to finish.
async fn send_token_replacement(
    client: &lpm_registry::RegistryClient,
    url: &str,
    body: &serde_json::Value,
    rollback: SetupRollback<'_>,
) -> Result<reqwest::Response, LpmError> {
    match client.post_json_raw_status_with_recovery(url, body).await {
        Ok(response) => Ok(response),
        Err(error @ (LpmError::AuthRequired | LpmError::SessionExpired)) => {
            Err(rollback_files(error, rollback))
        }
        Err(error) => Err(pending_recovery_error(format!(
            "the setup-token replacement response was not received: {error}"
        ))),
    }
}

/// Whether the Registry refused the replacement because the token it was to
/// retire is revoked, or isn't a setup token of this account.
fn refused_inactive_predecessor(error: Option<&serde_json::Value>) -> bool {
    error
        .and_then(|error| error.get("code"))
        .and_then(serde_json::Value::as_str)
        == Some("previous_token_not_found")
}

/// The error a refused replacement ends setup with, after restoring `.npmrc`.
fn replacement_client_error(
    status: reqwest::StatusCode,
    parsed: Result<serde_json::Value, LpmError>,
    pending_token: &str,
    rollback: SetupRollback<'_>,
) -> LpmError {
    let Ok(error) = parsed else {
        return rollback_files(
            LpmError::Registry(format!(
                "invalid project token replacement error response ({status})"
            )),
            rollback,
        );
    };
    let message = error
        .get("error")
        .and_then(serde_json::Value::as_str)
        .unwrap_or("project token replacement failed");
    let message = sanitize_registry_message(message, pending_token);
    rollback_files(
        LpmError::Registry(format!("{message} ({status})")),
        rollback,
    )
}

fn rollback_files(primary: LpmError, rollback: SetupRollback<'_>) -> LpmError {
    combine_rollback_error(primary, rollback.restore())
}

fn pending_recovery_error(message: impl std::fmt::Display) -> LpmError {
    LpmError::Registry(format!(
        "{message}. The protected .npmrc retains the pending token; rerun `lpm setup local` with the same registry to finish safely"
    ))
}

fn sanitize_registry_message(message: &str, secret: &str) -> String {
    lpm_common::sanitize_terminal_inline(message).replace(secret, "<redacted>")
}

pub(super) struct SelfRevokeError {
    pub(super) error: LpmError,
    pub(super) may_have_committed: bool,
}

pub(super) async fn self_revoke_project_token(
    client: &RegistryClient,
    registry: &SetupRegistry,
    bearer: &str,
) -> Result<(), SelfRevokeError> {
    let url = registry.token_url("revoke-project");
    let isolated_client = client.clone_with_static_token(bearer);
    let response = match isolated_client
        .post_json_raw_status(&url, &serde_json::json!({ "self": true }))
        .await
    {
        Ok(response) => response,
        Err(error) => {
            return Err(SelfRevokeError {
                error: LpmError::Registry(format!(
                    "project token self-revocation response was not received: {error}"
                )),
                may_have_committed: true,
            });
        }
    };
    let status = response.status();
    if matches!(
        status,
        reqwest::StatusCode::UNAUTHORIZED | reqwest::StatusCode::NOT_FOUND
    ) {
        return Ok(());
    }
    let body: serde_json::Value =
        lpm_registry::parse_capped_api_json(response, "project token self-revocation response")
            .await
            .map_err(|error| SelfRevokeError {
                error,
                may_have_committed: status.is_success() || status.is_server_error(),
            })?;
    if !status.is_success() {
        let message = body
            .get("error")
            .and_then(serde_json::Value::as_str)
            .unwrap_or("project token self-revocation failed");
        return Err(SelfRevokeError {
            error: LpmError::Registry(format!(
                "{} ({status})",
                sanitize_registry_message(message, bearer)
            )),
            may_have_committed: status.is_server_error(),
        });
    }
    let returned_token_id = body
        .get("tokenId")
        .and_then(serde_json::Value::as_str)
        .filter(|token_id| valid_token_id(token_id));
    if body.get("revoked").and_then(serde_json::Value::as_bool) != Some(true)
        || returned_token_id.is_none()
    {
        return Err(SelfRevokeError {
            error: LpmError::Registry("invalid project token self-revocation response".into()),
            may_have_committed: true,
        });
    }
    Ok(())
}

pub(super) fn write_npmrc_if_unchanged(
    path: &Path,
    expected: &str,
    replacement: &str,
) -> Result<(), LpmError> {
    let current = match lpm_common::read_text_file_capped_nofollow(
        path,
        lpm_common::NPMRC_FILE_SIZE_CAP_BYTES,
    ) {
        Ok(current) => current,
        Err(lpm_common::BoundedReadError::NotFound { .. }) => String::new(),
        Err(error) => return Err(error.into()),
    };
    if current != expected {
        return Err(LpmError::Script(format!(
            "{} changed concurrently; refusing to overwrite it",
            path.display()
        )));
    }
    write_token_npmrc(path, replacement).map_err(LpmError::Io)
}

/// Writes an `.npmrc` that can hold a token, readable by its owner alone,
/// whatever access its directory hands down.
fn write_token_npmrc(path: &Path, contents: &str) -> std::io::Result<()> {
    lpm_common::write_file_atomic_with_options(
        path,
        contents,
        lpm_common::AtomicWriteOptions::new()
            .owner_only()
            .sync_file(),
    )
}

pub(super) fn restore_file_if_unchanged(
    path: &Path,
    expected_current: &str,
    original: Option<&str>,
    cap: u64,
    sensitive: bool,
) -> Result<(), String> {
    let current = match lpm_common::read_text_file_capped_nofollow(path, cap) {
        Ok(current) => Some(current),
        Err(lpm_common::BoundedReadError::NotFound { .. }) => None,
        Err(error) => return Err(error.to_string()),
    };
    if current.as_deref() == original {
        return Ok(());
    }
    if current.as_deref() != Some(expected_current) {
        return Err(format!(
            "{} changed concurrently; refusing to overwrite it",
            path.display()
        ));
    }

    match original {
        Some(contents) if sensitive => {
            write_token_npmrc(path, contents).map_err(|error| error.to_string())
        }
        Some(contents) => {
            lpm_common::write_file_atomic(path, contents).map_err(|error| error.to_string())
        }
        None => std::fs::remove_file(path).map_err(|error| error.to_string()),
    }
}

fn combine_rollback_error(primary: LpmError, rollback_errors: Vec<String>) -> LpmError {
    if rollback_errors.is_empty() {
        primary
    } else {
        LpmError::Script(format!(
            "{primary}; rollback incomplete: {}",
            rollback_errors.join("; ")
        ))
    }
}

fn pending_setup_token(
    existing: &str,
    expected_auth_scope: &str,
) -> Result<Option<PendingSetupToken>, LpmError> {
    let lines = local_generated_lines(existing);
    let Some(token_id) = parse_single_marker(&lines, PENDING_TOKEN_ID_PREFIX, valid_token_id)?
    else {
        return Ok(None);
    };
    let token = auth_token_from_lines(&lines, expected_auth_scope)?.ok_or_else(|| {
        LpmError::Script(
            "the pending setup-token block is missing its protected bearer; restore the file or remove the generated block before retrying".into(),
        )
    })?;
    if !valid_generated_project_token(token) {
        return Err(LpmError::Script(
            "the pending setup-token block contains an invalid bearer".into(),
        ));
    }
    if lines.iter().any(|line| {
        line.starts_with(PREVIOUS_TOKEN_ID_PREFIX) || line.starts_with(PREVIOUS_TOKEN_HASH_PREFIX)
    }) {
        return Err(LpmError::Script(
            "the pending setup-token block uses legacy predecessor ID/hash markers that cannot prove possession. Revoke the pending and predecessor setup tokens in the LPM.dev dashboard, then remove the generated block before retrying".into(),
        ));
    }
    let previous_bearer =
        parse_single_marker(&lines, PREVIOUS_TOKEN_BEARER_PREFIX, valid_stored_bearer)?;
    if previous_bearer.as_deref() == Some(token) {
        return Err(LpmError::Script(
            "the pending setup-token block reuses the predecessor bearer".into(),
        ));
    }
    Ok(Some(PendingSetupToken {
        token: token.to_string(),
        token_id,
        previous_bearer,
    }))
}

fn local_project_token_bearer(
    existing: &str,
    expected_auth_scope: &str,
) -> Result<Option<String>, LpmError> {
    let lines = local_generated_lines(existing);
    if lines.is_empty() {
        return Ok(None);
    }
    let bearer = auth_token_from_lines(&lines, expected_auth_scope)?;
    if bearer.is_some_and(|value| !valid_stored_bearer(value)) {
        return Err(LpmError::Script(
            "the generated setup-local block contains an invalid bearer".into(),
        ));
    }
    Ok(bearer.map(str::to_string))
}

pub(super) fn local_setup_registry_url(existing: &str) -> Option<String> {
    registry_url_from_lines(&local_generated_lines(existing)).map(normalize_registry_url)
}

pub(super) fn setup_ci_predecessor_bearer(
    existing: &str,
    expected_auth_scope: &str,
) -> Result<Option<String>, LpmError> {
    reject_legacy_ci_retirement_state(existing)?;
    let local_lines = local_generated_lines(existing);
    if local_lines
        .iter()
        .any(|line| line.starts_with(PENDING_TOKEN_ID_PREFIX))
    {
        return Err(LpmError::Script(
            "setup local has a pending token replacement. Run `lpm setup local` with the same registry to finish it before switching to `lpm setup ci npmrc`".into(),
        ));
    }
    local_project_token_bearer(existing, expected_auth_scope)
}

pub(super) fn setup_ci_pending_retirement(
    existing: &str,
    expected_auth_scope: &str,
) -> Result<Option<(String, String)>, LpmError> {
    let lines = ci_generated_lines(existing);
    let predecessor = parse_single_marker(&lines, CI_RETIRE_BEARER_PREFIX, valid_stored_bearer)?;
    let Some(predecessor) = predecessor else {
        return Ok(None);
    };
    let replacement = auth_token_from_lines(&lines, expected_auth_scope)?.ok_or_else(|| {
        LpmError::Script(
            "the pending CI token-retirement block is missing its replacement bearer".into(),
        )
    })?;
    if !valid_stored_bearer(replacement) || replacement == predecessor {
        return Err(LpmError::Script(
            "the pending CI token-retirement block contains invalid recovery credentials".into(),
        ));
    }
    Ok(Some((replacement.to_string(), predecessor)))
}

pub(super) fn setup_ci_registry_url(existing: &str) -> Option<String> {
    registry_url_from_lines(&ci_generated_lines(existing)).map(normalize_registry_url)
}

fn reject_legacy_ci_retirement_state(existing: &str) -> Result<(), LpmError> {
    let ci_lines = ci_generated_lines(existing);
    if ci_lines.iter().any(|line| {
        line.starts_with(RETIRE_TOKEN_ID_PREFIX) || line.starts_with(RETIRE_TOKEN_HASH_PREFIX)
    }) {
        return Err(LpmError::Script(
            "the generated CI block contains legacy pending token-retirement markers that cannot prove possession. Revoke the referenced setup token in the LPM.dev dashboard, then remove the generated block before retrying".into(),
        ));
    }
    Ok(())
}

fn local_generated_lines(existing: &str) -> Vec<&str> {
    generated_lines(existing, GENERATED_HEADER)
}

fn ci_generated_lines(existing: &str) -> Vec<&str> {
    generated_lines(existing, CI_GENERATED_HEADER)
}

fn generated_lines<'a>(existing: &'a str, header: &str) -> Vec<&'a str> {
    let mut lines = Vec::new();
    let mut in_generated_block = false;
    for line in existing.lines() {
        if line == header {
            in_generated_block = true;
            continue;
        }
        if !in_generated_block {
            continue;
        }
        if line == GENERATED_END || is_generated_header(line) {
            break;
        }
        lines.push(line);
    }
    lines
}

fn parse_single_marker(
    lines: &[&str],
    prefix: &str,
    validate: impl Fn(&str) -> bool,
) -> Result<Option<String>, LpmError> {
    let mut found = None;
    for value in lines.iter().filter_map(|line| line.strip_prefix(prefix)) {
        if !validate(value) {
            return Err(LpmError::Script(format!(
                "the generated setup block contains an invalid `{}` marker",
                prefix.trim()
            )));
        }
        if found.replace(value.to_string()).is_some() {
            return Err(LpmError::Script(format!(
                "the generated setup block contains duplicate `{}` markers",
                prefix.trim()
            )));
        }
    }
    Ok(found)
}

fn auth_token_from_lines<'a>(
    lines: &'a [&str],
    expected_auth_scope: &str,
) -> Result<Option<&'a str>, LpmError> {
    let expected_prefix = format!("{expected_auth_scope}:_authToken=");
    let mut found = None;
    for line in lines.iter().filter(|line| line.contains("/:_authToken=")) {
        let Some(token) = line.strip_prefix(&expected_prefix) else {
            return Err(LpmError::Script(
                "the generated setup block contains a bearer for a different registry scope".into(),
            ));
        };
        if token.is_empty() {
            return Err(LpmError::Script(
                "the generated setup block contains an empty bearer".into(),
            ));
        }
        if found.replace(token).is_some() {
            return Err(LpmError::Script(
                "the generated setup block contains duplicate bearer lines".into(),
            ));
        }
    }
    Ok(found)
}

fn registry_url_from_lines<'a>(lines: &'a [&str]) -> Option<&'a str> {
    lines
        .iter()
        .find_map(|line| line.strip_prefix("@lpm.dev:registry="))
}

fn normalize_registry_url(url: &str) -> String {
    url.trim_end_matches('/').to_string()
}

fn generate_project_token() -> Result<String, LpmError> {
    let mut bytes = [0_u8; 32];
    rand::rngs::SysRng
        .try_fill_bytes(&mut bytes)
        .map_err(|error| {
            LpmError::Script(format!(
                "failed to generate project token securely: {error}"
            ))
        })?;
    Ok(format!("lpm_{}", hex::encode(bytes)))
}

fn generate_uuid_v4() -> Result<String, LpmError> {
    let mut bytes = [0_u8; 16];
    rand::rngs::SysRng
        .try_fill_bytes(&mut bytes)
        .map_err(|error| {
            LpmError::Script(format!(
                "failed to generate project token ID securely: {error}"
            ))
        })?;
    bytes[6] = (bytes[6] & 0x0f) | 0x40;
    bytes[8] = (bytes[8] & 0x3f) | 0x80;
    let encoded = hex::encode(bytes);
    Ok(format!(
        "{}-{}-{}-{}-{}",
        &encoded[..8],
        &encoded[8..12],
        &encoded[12..16],
        &encoded[16..20],
        &encoded[20..]
    ))
}

fn valid_token_id(token_id: &str) -> bool {
    let bytes = token_id.as_bytes();
    bytes.len() == 36
        && bytes.iter().enumerate().all(|(index, byte)| {
            if matches!(index, 8 | 13 | 18 | 23) {
                *byte == b'-'
            } else {
                byte.is_ascii_hexdigit()
            }
        })
}

fn valid_token_hash(token_hash: &str) -> bool {
    token_hash.len() == 64
        && token_hash
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
}

fn valid_stored_bearer(token: &str) -> bool {
    !token.is_empty()
        && token.len() <= 4096
        && token.bytes().all(|byte| {
            byte.is_ascii_alphanumeric()
                || matches!(byte, b'-' | b'.' | b'_' | b'~' | b'+' | b'/' | b'=')
        })
}

fn valid_generated_project_token(token: &str) -> bool {
    token.strip_prefix("lpm_").is_some_and(valid_token_hash)
}

fn replace_generated_block(existing: &str, generated: &str) -> String {
    let kept = lines_outside_generated_blocks(existing);
    let prefix = kept.join("\n").trim().to_string();
    if prefix.is_empty() {
        format!("{generated}\n")
    } else {
        format!("{prefix}\n\n{generated}\n")
    }
}

/// The lines of `existing` that no generated block holds, including an
/// unterminated block's marker, registry and bearer lines.
pub(super) fn lines_outside_generated_blocks(existing: &str) -> Vec<&str> {
    let lines: Vec<_> = existing.lines().collect();
    let mut kept = Vec::with_capacity(lines.len());
    let mut index = 0;
    while index < lines.len() {
        let line = lines[index];
        if is_generated_header(line) {
            let next_boundary = lines[index + 1..]
                .iter()
                .position(|candidate| *candidate == GENERATED_END || is_generated_header(candidate))
                .map(|offset| index + 1 + offset);
            index = match next_boundary {
                Some(end) if lines[end] == GENERATED_END => end + 1,
                _ => {
                    let mut end = index + 1;
                    while lines.get(end).is_some_and(|line| {
                        line.starts_with(TOKEN_ID_PREFIX)
                            || line.starts_with(PENDING_TOKEN_ID_PREFIX)
                            || line.starts_with(PREVIOUS_TOKEN_ID_PREFIX)
                            || line.starts_with(PREVIOUS_TOKEN_HASH_PREFIX)
                            || line.starts_with(PREVIOUS_TOKEN_BEARER_PREFIX)
                            || line.starts_with(RETIRE_TOKEN_ID_PREFIX)
                            || line.starts_with(RETIRE_TOKEN_HASH_PREFIX)
                            || line.starts_with(CI_RETIRE_BEARER_PREFIX)
                            || line.starts_with("@lpm.dev:registry=")
                            || line.contains("/:_authToken=")
                    }) {
                        end += 1;
                    }
                    end
                }
            };
            continue;
        }
        kept.push(line);
        index += 1;
    }
    kept
}

fn is_generated_header(line: &str) -> bool {
    line == GENERATED_HEADER || line == CI_GENERATED_HEADER
}

fn format_days_label(days: u32) -> String {
    if days == 1 {
        "1 day".to_string()
    } else {
        format!("{days} days")
    }
}

