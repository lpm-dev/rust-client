use crate::install_ui;
use lpm_common::LpmError;
use lpm_registry::RegistryClient;
use rand::RngCore;
use serde::Deserialize;
use sha2::{Digest, Sha256};
use std::path::Path;

const GENERATED_HEADER: &str = "# LPM Registry (generated by lpm setup local — do not commit)";
const CI_GENERATED_HEADER: &str = "# LPM Registry (generated by lpm setup ci npmrc)";
const TOKEN_ID_PREFIX: &str = "# LPM project token id: ";
const PENDING_TOKEN_ID_PREFIX: &str = "# LPM pending project token id: ";
const PREVIOUS_TOKEN_ID_PREFIX: &str = "# LPM previous project token id: ";
const PREVIOUS_TOKEN_HASH_PREFIX: &str = "# LPM previous project token hash: ";
pub(super) const RETIRE_TOKEN_ID_PREFIX: &str = "# LPM pending project token retirement id: ";
pub(super) const RETIRE_TOKEN_HASH_PREFIX: &str = "# LPM pending project token retirement hash: ";
const GENERATED_END: &str = "# End LPM Registry";

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct TokenReplaceResponse {
    token_id: String,
    scope: String,
    expires_at: String,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub(super) enum ProjectTokenReference {
    Id(String),
    Hash(String),
}

impl ProjectTokenReference {
    fn add_to_body(&self, body: &mut serde_json::Value, previous: bool) {
        let key = match (self, previous) {
            (Self::Id(_), true) => "previousTokenId",
            (Self::Hash(_), true) => "previousTokenHash",
            (Self::Id(_), false) => "tokenId",
            (Self::Hash(_), false) => "tokenHash",
        };
        body[key] = serde_json::Value::String(self.value().to_string());
    }

    pub(super) fn retirement_marker(&self) -> String {
        match self {
            Self::Id(value) => format!("{RETIRE_TOKEN_ID_PREFIX}{value}"),
            Self::Hash(value) => format!("{RETIRE_TOKEN_HASH_PREFIX}{value}"),
        }
    }

    fn value(&self) -> &str {
        match self {
            Self::Id(value) | Self::Hash(value) => value,
        }
    }
}

struct PendingSetupToken {
    token: String,
    token_id: String,
    previous: Option<ProjectTokenReference>,
}

#[derive(Clone, Copy)]
struct SetupRollback<'a> {
    gitignore_path: &'a Path,
    expected_gitignore: &'a str,
    original_gitignore: Option<&'a str>,
    npmrc: Option<(&'a Path, &'a str, &'a str)>,
}

impl<'a> SetupRollback<'a> {
    fn new(
        gitignore_path: &'a Path,
        expected_gitignore: &'a str,
        original_gitignore: Option<&'a str>,
    ) -> Self {
        Self {
            gitignore_path,
            expected_gitignore,
            original_gitignore,
            npmrc: None,
        }
    }

    fn with_npmrc(
        mut self,
        npmrc_path: &'a Path,
        expected_npmrc: &'a str,
        original_npmrc: &'a str,
    ) -> Self {
        self.npmrc = Some((npmrc_path, expected_npmrc, original_npmrc));
        self
    }

    fn restore(self) -> Vec<String> {
        let mut errors = Vec::with_capacity(2);
        if let Some((npmrc_path, expected_npmrc, original_npmrc)) = self.npmrc
            && let Err(error) = restore_file_if_unchanged(
                npmrc_path,
                expected_npmrc,
                Some(original_npmrc),
                lpm_common::NPMRC_FILE_SIZE_CAP_BYTES,
                true,
            )
        {
            errors.push(format!("failed to restore .npmrc: {error}"));
        }
        if let Err(error) = restore_file_if_unchanged(
            self.gitignore_path,
            self.expected_gitignore,
            self.original_gitignore,
            lpm_common::CONFIG_FILE_SIZE_CAP_BYTES,
            false,
        ) {
            errors.push(format!("failed to restore .gitignore: {error}"));
        }
        errors
    }
}

/// Generate a read-only .npmrc token for local development.
///
/// Creates a scoped read-only token and writes it to the project's .npmrc.
/// Also ensures .npmrc is in .gitignore to prevent accidental commits.
///
/// Default: scoped config (`@lpm.dev:registry=`) — only LPM packages go through lpm.dev.
pub async fn run(
    client: &RegistryClient,
    project_dir: &Path,
    registry_url: &str,
    days: u32,
    json_output: bool,
) -> Result<(), LpmError> {
    if !(1..=90).contains(&days) {
        return Err(LpmError::Script(
            "--days must be between 1 and 90".to_string(),
        ));
    }

    let pkg_json_path = project_dir.join("package.json");
    let npmrc_path = project_dir.join(".npmrc");
    let gitignore_path = project_dir.join(".gitignore");

    let package_json_content = match lpm_common::read_text_file_capped(
        &pkg_json_path,
        lpm_common::CONFIG_FILE_SIZE_CAP_BYTES,
    ) {
        Ok(content) => Some(content),
        Err(lpm_common::BoundedReadError::NotFound { .. }) => None,
        Err(error) => return Err(error.into()),
    };
    let existing_npmrc =
        match lpm_common::read_text_file_capped(&npmrc_path, lpm_common::NPMRC_FILE_SIZE_CAP_BYTES)
        {
            Ok(content) => content,
            Err(lpm_common::BoundedReadError::NotFound { .. }) => String::new(),
            Err(error) => return Err(error.into()),
        };
    let existing_gitignore = match lpm_common::read_text_file_capped(
        &gitignore_path,
        lpm_common::CONFIG_FILE_SIZE_CAP_BYTES,
    ) {
        Ok(content) => Some(content),
        Err(lpm_common::BoundedReadError::NotFound { .. }) => None,
        Err(error) => return Err(error.into()),
    };

    if package_json_content.is_none() && !json_output {
        install_ui::warn("No package.json found. Run this command in your project root.");
    }

    let project_name = if let Some(content) = package_json_content {
        serde_json::from_str::<serde_json::Value>(&content)
            .ok()
            .and_then(|v| v.get("name")?.as_str().map(|s| s.to_string()))
            .map_or_else(
                || "project".to_string(),
                |name| {
                    name.chars()
                        .map(|c| {
                            if c.is_alphanumeric() || c == '.' || c == '-' || c == '_' {
                                c
                            } else {
                                '-'
                            }
                        })
                        .collect::<String>()
                },
            )
    } else {
        "project".to_string()
    };

    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_err(|error| LpmError::Script(format!("system clock is before Unix epoch: {error}")))?
        .as_secs();
    let days_since_epoch = now / 86400;
    let today = format!("{days_since_epoch}");
    let token_name = format!("npmrc-{project_name}-{today}");

    let full_registry_url = if registry_url
        .trim_end_matches('/')
        .ends_with("/api/registry")
    {
        registry_url.trim_end_matches('/').to_string()
    } else {
        format!("{}/api/registry", registry_url.trim_end_matches('/'))
    };
    let registry_host = full_registry_url.replace("https:", "").replace("http:", "");
    let registry_line = format!("@lpm.dev:registry={full_registry_url}");
    if let Some(existing_registry) = local_setup_registry_url(&existing_npmrc)
        && existing_registry != full_registry_url
    {
        return Err(LpmError::Script(format!(
            "the setup-local token belongs to {existing_registry}; rerun with its registry to finish replacement safely"
        )));
    }
    let pending = match pending_setup_token(&existing_npmrc)? {
        Some(pending) => pending,
        None => PendingSetupToken {
            token: generate_project_token()?,
            token_id: generate_uuid_v4()?,
            previous: local_project_token_references(&existing_npmrc)?
                .into_iter()
                .next(),
        },
    };

    if !existing_npmrc.is_empty() {
        let has_custom_registry = existing_npmrc.lines().any(|line| {
            line.starts_with("registry=")
                && !line.contains("registry.npmjs.org")
                && !line.contains("lpm.dev")
        });
        if has_custom_registry && !json_output {
            install_ui::phase("Found existing custom default registry. Using scoped mode.");
        }
    }

    let current_gitignore = existing_gitignore.as_deref().unwrap_or_default();
    let mut gitignore_lines: Vec<&str> = current_gitignore
        .lines()
        .filter(|line| line.trim() != ".npmrc")
        .collect();
    gitignore_lines.push(".npmrc");
    let updated_gitignore = format!("{}\n", gitignore_lines.join("\n"));
    let gitignore_updated = updated_gitignore != current_gitignore;
    let rollback = SetupRollback::new(
        &gitignore_path,
        &updated_gitignore,
        existing_gitignore.as_deref(),
    );
    if gitignore_updated {
        lpm_common::write_file_atomic(&gitignore_path, &updated_gitignore)?;
    }

    let previous_marker = pending
        .previous
        .as_ref()
        .map_or_else(String::new, |reference| match reference {
            ProjectTokenReference::Id(value) => {
                format!("{PREVIOUS_TOKEN_ID_PREFIX}{value}\n")
            }
            ProjectTokenReference::Hash(value) => {
                format!("{PREVIOUS_TOKEN_HASH_PREFIX}{value}\n")
            }
        });
    let pending_config = format!(
        "{GENERATED_HEADER}\n{PENDING_TOKEN_ID_PREFIX}{}\n{previous_marker}{registry_line}\n{registry_host}/:_authToken={}\n{GENERATED_END}",
        pending.token_id, pending.token
    );
    let pending_content = replace_generated_block(&existing_npmrc, &pending_config);
    if let Err(error) = lpm_common::write_file_atomic_with_options(
        &npmrc_path,
        &pending_content,
        lpm_common::AtomicWriteOptions::new().unix_mode(0o600),
    ) {
        return Err(rollback_files(LpmError::Io(error), rollback));
    }
    let rollback = rollback.with_npmrc(&npmrc_path, &pending_content, &existing_npmrc);

    if !json_output {
        install_ui::phase("Creating read-only token...");
    }

    let mut body = serde_json::json!({
        "token": pending.token,
        "tokenId": pending.token_id,
        "scope": "read",
        "name": token_name,
        "expiryDays": days,
    });
    if let Some(previous) = &pending.previous {
        previous.add_to_body(&mut body, true);
    }
    let url = format!(
        "{}/api/registry/-/token/replace-project",
        registry_url.trim_end_matches('/')
    );
    let response = match client.post_json_raw_status(&url, &body).await {
        Ok(response) => response,
        Err(error) => {
            return Err(pending_recovery_error(format!(
                "the setup-token replacement response was not received: {error}"
            )));
        }
    };

    if !response.status().is_success() {
        let status = response.status();
        let parsed =
            lpm_registry::parse_capped_api_json(response, "project token replacement error").await;
        if !status.is_client_error() {
            let detail = parsed
                .ok()
                .and_then(|value: serde_json::Value| {
                    value
                        .get("error")
                        .and_then(serde_json::Value::as_str)
                        .map(|message| sanitize_registry_message(message, &pending.token))
                })
                .unwrap_or_else(|| "Registry returned an ambiguous failure".to_string());
            return Err(pending_recovery_error(format!("{detail} ({status})")));
        }
        let error: serde_json::Value = match parsed {
            Ok(error) => error,
            Err(_) => {
                return Err(rollback_files(
                    LpmError::Registry(format!(
                        "invalid project token replacement error response ({status})"
                    )),
                    rollback,
                ));
            }
        };
        let message = error
            .get("error")
            .and_then(serde_json::Value::as_str)
            .unwrap_or("project token replacement failed");
        let message = sanitize_registry_message(message, &pending.token);
        return Err(rollback_files(
            LpmError::Registry(format!("{message} ({status})")),
            rollback,
        ));
    }

    let replaced_value: serde_json::Value =
        match lpm_registry::parse_capped_api_json(response, "project token replacement response")
            .await
        {
            Ok(value) => value,
            Err(error) => {
                return Err(pending_recovery_error(sanitize_registry_message(
                    &error.to_string(),
                    &pending.token,
                )));
            }
        };
    let replaced: TokenReplaceResponse = match serde_json::from_value(replaced_value) {
        Ok(replaced) => replaced,
        Err(error) => {
            return Err(pending_recovery_error(format!(
                "invalid project token replacement response: {error}"
            )));
        }
    };
    if replaced.token_id != pending.token_id
        || replaced.scope != "read"
        || chrono::DateTime::parse_from_rfc3339(&replaced.expires_at).is_err()
    {
        return Err(pending_recovery_error(
            "invalid project token replacement response: expected the requested read-only token ID and a valid expiry",
        ));
    }
    let expires_at = replaced.expires_at;

    let lpm_config = format!(
        "{GENERATED_HEADER}\n{TOKEN_ID_PREFIX}{}\n{registry_line}\n{registry_host}/:_authToken={}\n{GENERATED_END}",
        pending.token_id, pending.token
    );
    let final_content = replace_generated_block(&pending_content, &lpm_config);
    if let Err(error) = lpm_common::write_file_atomic_with_options(
        &npmrc_path,
        &final_content,
        lpm_common::AtomicWriteOptions::new().unix_mode(0o600),
    ) {
        return Err(pending_recovery_error(format!(
            "the Registry committed the replacement, but .npmrc could not be finalized: {error}"
        )));
    }

    if !json_output {
        install_ui::done("Read-only token created.");
    }

    if json_output {
        let json = serde_json::json!({
            "success": true,
            "npmrc_path": npmrc_path.display().to_string(),
            "gitignore_path": gitignore_path.display().to_string(),
            "proxy": false,
            "scope": replaced.scope,
            "expires_at": expires_at,
            "expiry_days": days,
            "gitignore_updated": gitignore_updated,
        });
        let rendered = serde_json::to_string_pretty(&json).map_err(|error| {
            LpmError::Registry(format!("failed to encode JSON output: {error}"))
        })?;
        println!("{rendered}");
    } else {
        install_ui::done(".npmrc configured with read-only LPM token.");
        if gitignore_updated {
            install_ui::phase(".npmrc added to .gitignore to prevent token leaks.");
        }
        install_ui::phase("Only @lpm.dev packages will route through lpm.dev.");
        if !expires_at.is_empty() {
            install_ui::phase_line(crate::install_ui::terminal_line!(
                "{} {} ({})",
                install_ui::dim("Token expires:"),
                expires_at,
                install_ui::yellow(&format_days_label(days))
            ));
        }
        install_ui::phase("Run `lpm setup local` again to refresh when expired.");
    }

    Ok(())
}

fn rollback_files(primary: LpmError, rollback: SetupRollback<'_>) -> LpmError {
    combine_rollback_error(primary, rollback.restore())
}

fn pending_recovery_error(message: impl std::fmt::Display) -> LpmError {
    LpmError::Registry(format!(
        "{message}. The protected .npmrc retains the pending token; rerun `lpm setup local` with the same registry to finish safely"
    ))
}

fn sanitize_registry_message(message: &str, secret: &str) -> String {
    lpm_common::sanitize_terminal_inline(message).replace(secret, "<redacted>")
}

pub(super) async fn retire_project_token(
    client: &RegistryClient,
    registry_url: &str,
    reference: &ProjectTokenReference,
) -> Result<(), LpmError> {
    let url = format!(
        "{}/api/registry/-/token/revoke-project",
        registry_url.trim_end_matches('/')
    );
    let mut request = serde_json::json!({});
    reference.add_to_body(&mut request, false);
    let response = client
        .post_json_raw_status(&url, &request)
        .await
        .map_err(|error| {
            LpmError::Registry(format!(
                "project token retirement response was not received: {error}"
            ))
        })?;
    let status = response.status();
    if status == reqwest::StatusCode::NOT_FOUND {
        return Ok(());
    }
    let body: serde_json::Value =
        lpm_registry::parse_capped_api_json(response, "project token retirement response").await?;
    if !status.is_success() {
        let message = body
            .get("error")
            .and_then(serde_json::Value::as_str)
            .unwrap_or("project token retirement failed");
        return Err(LpmError::Registry(format!(
            "{} ({status})",
            lpm_common::sanitize_terminal_inline(message)
        )));
    }
    let returned_token_id = body
        .get("tokenId")
        .and_then(serde_json::Value::as_str)
        .filter(|token_id| valid_token_id(token_id));
    if body.get("revoked").and_then(serde_json::Value::as_bool) != Some(true)
        || returned_token_id.is_none()
        || matches!(
            reference,
            ProjectTokenReference::Id(expected)
                if returned_token_id != Some(expected.as_str())
        )
    {
        return Err(LpmError::Registry(
            "invalid project token retirement response".into(),
        ));
    }
    Ok(())
}

fn restore_file_if_unchanged(
    path: &Path,
    expected_current: &str,
    original: Option<&str>,
    cap: u64,
    sensitive: bool,
) -> Result<(), String> {
    let current = match lpm_common::read_text_file_capped(path, cap) {
        Ok(current) => Some(current),
        Err(lpm_common::BoundedReadError::NotFound { .. }) => None,
        Err(error) => return Err(error.to_string()),
    };
    if current.as_deref() == original {
        return Ok(());
    }
    if current.as_deref() != Some(expected_current) {
        return Err(format!(
            "{} changed concurrently; refusing to overwrite it",
            path.display()
        ));
    }

    match original {
        Some(contents) if sensitive => lpm_common::write_file_atomic_with_options(
            path,
            contents,
            lpm_common::AtomicWriteOptions::new().unix_mode(0o600),
        )
        .map_err(|error| error.to_string()),
        Some(contents) => {
            lpm_common::write_file_atomic(path, contents).map_err(|error| error.to_string())
        }
        None => std::fs::remove_file(path).map_err(|error| error.to_string()),
    }
}

fn combine_rollback_error(primary: LpmError, rollback_errors: Vec<String>) -> LpmError {
    if rollback_errors.is_empty() {
        primary
    } else {
        LpmError::Script(format!(
            "{primary}; rollback incomplete: {}",
            rollback_errors.join("; ")
        ))
    }
}

fn pending_setup_token(existing: &str) -> Result<Option<PendingSetupToken>, LpmError> {
    let lines = local_generated_lines(existing);
    let Some(token_id) = parse_single_marker(&lines, PENDING_TOKEN_ID_PREFIX, valid_token_id)?
    else {
        return Ok(None);
    };
    let token = auth_token_from_lines(&lines).ok_or_else(|| {
        LpmError::Script(
            "the pending setup-token block is missing its protected bearer; restore the file or remove the generated block before retrying".into(),
        )
    })?;
    if !valid_generated_project_token(token) {
        return Err(LpmError::Script(
            "the pending setup-token block contains an invalid bearer".into(),
        ));
    }
    let previous_id = parse_single_marker(&lines, PREVIOUS_TOKEN_ID_PREFIX, valid_token_id)?;
    let previous_hash = parse_single_marker(&lines, PREVIOUS_TOKEN_HASH_PREFIX, valid_token_hash)?;
    if previous_id.is_some() && previous_hash.is_some() {
        return Err(LpmError::Script(
            "the pending setup-token block contains conflicting predecessor references".into(),
        ));
    }
    Ok(Some(PendingSetupToken {
        token: token.to_string(),
        token_id,
        previous: previous_id
            .map(ProjectTokenReference::Id)
            .or_else(|| previous_hash.map(ProjectTokenReference::Hash)),
    }))
}

pub(super) fn local_project_token_references(
    existing: &str,
) -> Result<Vec<ProjectTokenReference>, LpmError> {
    let lines = local_generated_lines(existing);
    if lines.is_empty() {
        return Ok(Vec::new());
    }

    let pending_id = parse_single_marker(&lines, PENDING_TOKEN_ID_PREFIX, valid_token_id)?;
    let previous_id = parse_single_marker(&lines, PREVIOUS_TOKEN_ID_PREFIX, valid_token_id)?;
    let previous_hash = parse_single_marker(&lines, PREVIOUS_TOKEN_HASH_PREFIX, valid_token_hash)?;
    if previous_id.is_some() && previous_hash.is_some() {
        return Err(LpmError::Script(
            "the generated setup block contains conflicting predecessor references".into(),
        ));
    }
    if let Some(pending_id) = pending_id {
        let mut references = Vec::with_capacity(2);
        references.push(ProjectTokenReference::Id(pending_id));
        if let Some(previous_id) = previous_id {
            references.push(ProjectTokenReference::Id(previous_id));
        } else if let Some(previous_hash) = previous_hash {
            references.push(ProjectTokenReference::Hash(previous_hash));
        }
        return Ok(references);
    }

    if let Some(token_id) = parse_single_marker(&lines, TOKEN_ID_PREFIX, valid_token_id)? {
        return Ok(vec![ProjectTokenReference::Id(token_id)]);
    }
    Ok(auth_token_from_lines(&lines)
        .map(|token| ProjectTokenReference::Hash(hex::encode(Sha256::digest(token.as_bytes()))))
        .into_iter()
        .collect())
}

pub(super) fn local_setup_registry_url(existing: &str) -> Option<String> {
    registry_url_from_lines(&local_generated_lines(existing)).map(normalize_registry_url)
}

pub(super) fn pending_retirement_references(
    existing: &str,
) -> Result<Vec<ProjectTokenReference>, LpmError> {
    let mut references = Vec::new();
    for line in existing.lines() {
        if let Some(value) = line.strip_prefix(RETIRE_TOKEN_ID_PREFIX) {
            if !valid_token_id(value) {
                return Err(LpmError::Script(
                    "the generated CI block contains an invalid pending token ID".into(),
                ));
            }
            push_unique(
                &mut references,
                ProjectTokenReference::Id(value.to_string()),
            );
        } else if let Some(value) = line.strip_prefix(RETIRE_TOKEN_HASH_PREFIX) {
            if !valid_token_hash(value) {
                return Err(LpmError::Script(
                    "the generated CI block contains an invalid pending token hash".into(),
                ));
            }
            push_unique(
                &mut references,
                ProjectTokenReference::Hash(value.to_string()),
            );
        }
    }
    Ok(references)
}

fn local_generated_lines(existing: &str) -> Vec<&str> {
    let mut lines = Vec::new();
    let mut in_local_block = false;
    for line in existing.lines() {
        if line == GENERATED_HEADER {
            in_local_block = true;
            continue;
        }
        if !in_local_block {
            continue;
        }
        if line == GENERATED_END || is_generated_header(line) {
            break;
        }
        lines.push(line);
    }
    lines
}

fn parse_single_marker(
    lines: &[&str],
    prefix: &str,
    validate: impl Fn(&str) -> bool,
) -> Result<Option<String>, LpmError> {
    let mut found = None;
    for value in lines.iter().filter_map(|line| line.strip_prefix(prefix)) {
        if !validate(value) {
            return Err(LpmError::Script(format!(
                "the generated setup block contains an invalid `{}` marker",
                prefix.trim()
            )));
        }
        if found.replace(value.to_string()).is_some() {
            return Err(LpmError::Script(format!(
                "the generated setup block contains duplicate `{}` markers",
                prefix.trim()
            )));
        }
    }
    Ok(found)
}

fn auth_token_from_lines<'a>(lines: &'a [&str]) -> Option<&'a str> {
    lines
        .iter()
        .find_map(|line| line.split_once("/:_authToken=").map(|(_, token)| token))
        .filter(|token| !token.is_empty())
}

fn registry_url_from_lines<'a>(lines: &'a [&str]) -> Option<&'a str> {
    lines
        .iter()
        .find_map(|line| line.strip_prefix("@lpm.dev:registry="))
}

fn normalize_registry_url(url: &str) -> String {
    url.trim_end_matches('/').to_string()
}

fn push_unique(references: &mut Vec<ProjectTokenReference>, reference: ProjectTokenReference) {
    if !references.contains(&reference) {
        references.push(reference);
    }
}

fn generate_project_token() -> Result<String, LpmError> {
    let mut bytes = [0_u8; 32];
    rand::rngs::OsRng
        .try_fill_bytes(&mut bytes)
        .map_err(|error| {
            LpmError::Script(format!(
                "failed to generate project token securely: {error}"
            ))
        })?;
    Ok(format!("lpm_{}", hex::encode(bytes)))
}

fn generate_uuid_v4() -> Result<String, LpmError> {
    let mut bytes = [0_u8; 16];
    rand::rngs::OsRng
        .try_fill_bytes(&mut bytes)
        .map_err(|error| {
            LpmError::Script(format!(
                "failed to generate project token ID securely: {error}"
            ))
        })?;
    bytes[6] = (bytes[6] & 0x0f) | 0x40;
    bytes[8] = (bytes[8] & 0x3f) | 0x80;
    let encoded = hex::encode(bytes);
    Ok(format!(
        "{}-{}-{}-{}-{}",
        &encoded[..8],
        &encoded[8..12],
        &encoded[12..16],
        &encoded[16..20],
        &encoded[20..]
    ))
}

fn valid_token_id(token_id: &str) -> bool {
    let bytes = token_id.as_bytes();
    bytes.len() == 36
        && bytes.iter().enumerate().all(|(index, byte)| {
            if matches!(index, 8 | 13 | 18 | 23) {
                *byte == b'-'
            } else {
                byte.is_ascii_hexdigit()
            }
        })
}

fn valid_token_hash(token_hash: &str) -> bool {
    token_hash.len() == 64
        && token_hash
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
}

fn valid_generated_project_token(token: &str) -> bool {
    token.strip_prefix("lpm_").is_some_and(valid_token_hash)
}

fn replace_generated_block(existing: &str, generated: &str) -> String {
    let lines: Vec<_> = existing.lines().collect();
    let mut kept = Vec::with_capacity(lines.len());
    let mut index = 0;
    while index < lines.len() {
        let line = lines[index];
        if is_generated_header(line) {
            let next_boundary = lines[index + 1..]
                .iter()
                .position(|candidate| *candidate == GENERATED_END || is_generated_header(candidate))
                .map(|offset| index + 1 + offset);
            index = match next_boundary {
                Some(end) if lines[end] == GENERATED_END => end + 1,
                _ => {
                    let mut end = index + 1;
                    while lines.get(end).is_some_and(|line| {
                        line.starts_with(TOKEN_ID_PREFIX)
                            || line.starts_with(PENDING_TOKEN_ID_PREFIX)
                            || line.starts_with(PREVIOUS_TOKEN_ID_PREFIX)
                            || line.starts_with(PREVIOUS_TOKEN_HASH_PREFIX)
                            || line.starts_with(RETIRE_TOKEN_ID_PREFIX)
                            || line.starts_with(RETIRE_TOKEN_HASH_PREFIX)
                            || line.starts_with("@lpm.dev:registry=")
                            || line.contains("/:_authToken=")
                    }) {
                        end += 1;
                    }
                    end
                }
            };
            continue;
        }
        kept.push(line);
        index += 1;
    }
    let prefix = kept.join("\n").trim().to_string();
    if prefix.is_empty() {
        format!("{generated}\n")
    } else {
        format!("{prefix}\n\n{generated}\n")
    }
}

fn is_generated_header(line: &str) -> bool {
    line == GENERATED_HEADER || line == CI_GENERATED_HEADER
}

fn format_days_label(days: u32) -> String {
    if days == 1 {
        "1 day".to_string()
    } else {
        format!("{days} days")
    }
}
